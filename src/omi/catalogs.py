RULE_LIMITS = {"tokens": 2000, "rule_tokens": 800}  # .omi/config.json "rule_limits" overrides (PO only)


def rule_limits(root):
    cfg = Path(root) / ".omi" / "config.json"
    over = json.loads(cfg.read_text(encoding="utf-8")).get("rule_limits", {}) if cfg.exists() else {}
    return RULE_LIMITS | over


def load_rules(root):
    """{id: (file, globs, tokens, problems)} of every .omi/rules/<id>.md."""
    cap = rule_limits(root)["rule_tokens"]
    found = {}
    for f in sorted((Path(root) / ".omi" / "rules").glob("*.md")):
        if f.name == "CATALOG.md":
            continue
        m, n = core.meta(f), core.tokens(f)
        globs = core.split(m.get("applies"))
        errs = ([f"id `{m.get('id')}` differs from file name"] if m.get("id") != f.stem else []) \
            + ([] if m.get("summary") else ["missing `summary`"]) + ([] if globs else ["needs at least one `applies` glob"]) \
            + ([f"{n} tokens, at most {cap} per rule"] if n > cap else [])
        found[f.stem] = (f, globs, n, errs)
    return found


def rules_catalog(root):
    """Write .omi/rules/CATALOG.md: `- id: summary (applies: globs) [~N tokens]`; exits listing invalid rules."""
    rules = load_rules(root)
    bad = [f"{rid}: {e}" for rid, (_, _, _, errs) in rules.items() for e in errs]
    if bad:
        sys.exit("rules check failed:\n" + "\n".join(bad))
    lines = ["# Rule catalog", "", "<!-- generated by `python -m omi rules`; do not edit -->"]
    for rid, (f, globs, n, _) in rules.items():
        lines.append(f"- {rid}: {' '.join(core.meta(f)['summary'].split())} (applies: {', '.join(globs)}) [~{n} tokens]")
    out = Path(root) / ".omi" / "rules" / "CATALOG.md"
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {out} ({len(lines) - 3} rules)")


def rule_matches(glob, scope_globs):
    return any(fnmatch(s, glob) or fnmatch(s, glob.removeprefix("**/")) for s in scope_globs)


def task_rules(root, scope):
    """Rule files whose `applies` matches the task scope; exits naming each rule when over the rule budget."""
    lim = rule_limits(root)
    tracked = (core.git(root, "ls-files") or "").splitlines()  # a broad scope (`src/**`) matches the files inside it too
    scope = scope + [f for f in tracked if any(fnmatch(f, g) for g in scope)]
    matched = [(rid, f, n, errs) for rid, (f, globs, n, errs) in load_rules(root).items()
               if any(rule_matches(g, scope) for g in globs)]
    bad = [f"{rid}: {e}" for rid, _, _, errs in matched for e in errs]
    if bad:
        sys.exit("rules check failed:\n" + "\n".join(bad))
    hit = [(rid, f, n) for rid, f, n, _ in matched]
    if sum(n for _, _, n in hit) > lim["tokens"] or any(n > lim["rule_tokens"] for _, _, n in hit):
        sys.exit(f"rule budget: at most {lim['tokens']} tokens in total, {lim['rule_tokens']} per rule. Only the PO can raise it. Rules: "
                 + ", ".join(f"{rid} {n} tokens" for rid, _, n in hit))
    return [f for _, f, _ in hit]


