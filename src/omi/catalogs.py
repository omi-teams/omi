ROLE_KEYS = ("role", "model", "effort", "access", "skills", "summary")


def agents_dir(root):
    d = Path(root) / ".omi" / "agents"
    return d if any(f.name != "CATALOG.md" for f in d.glob("*.md")) else core.TEMPLATE / "dot-omi" / "agents"


def load_roles(root):
    """{role: frontmatter} of every .omi/agents/<role>.md; exits on a malformed role file."""
    roles = {}
    for f in sorted(agents_dir(root).glob("*.md")):
        if f.name == "CATALOG.md":
            continue
        m = core.meta(f)
        errs = [f"missing `{k}`" for k in ROLE_KEYS if k not in m or (k != "skills" and not m[k])]
        if m.get("role") and m["role"] != f.stem:
            errs.append(f"role `{m['role']}` differs from file name")
        if not f.stem.startswith("omi-agent-"):
            errs.append(f"role `{f.stem}` must start with `omi-agent-`")
        if m.get("access") not in (None, "write", "read"):
            errs.append("access is not write|read")
        if m.get("tool") not in (None, "", "claude", "codex"):
            errs.append("tool is not claude|codex")
        if errs:
            sys.exit(f"agent {f.name}: {'; '.join(errs)}")
        roles[f.stem] = m
    return roles


def get_role(root, role):
    roles = load_roles(root)
    if role not in roles:
        sys.exit(f"unknown role `{role}`: role names start with omi-agent-; known roles are {', '.join(roles)}. Nothing changed.")
    return roles[role]


def agents_catalog(root):
    """Write .omi/agents/CATALOG.md: `- role (access, model/effort): when to use`."""
    lines = ["# Agent catalog", "", "<!-- generated by `python -m omi agents`; do not edit -->"]
    for role, m in load_roles(root).items():
        lines.append(f"- {role} ({m['access']}, {m['model']}/{m['effort']}): {' '.join(m['summary'].split())}")
    count = len(lines) - 3
    cfg = Path(root) / ".omi" / "config.json"
    config = json.loads(cfg.read_text(encoding="utf-8")) if cfg.exists() else {}
    lines.extend(["", "## Models", "", "Recommendations from the model research; task quality and cost are not benchmarked."])
    for tool, notes in config.get("model_notes", {}).items():
        lines.extend(["", f"### {tool}"])
        for kind in ("models", "efforts"):
            for name, note in notes.get(kind, {}).items():
                key = f"model_notes.{tool}.{kind}.{name}"
                for field in ("fits", "avoid"):
                    if not isinstance(note, dict) or not isinstance(note.get(field), str) or not note[field].strip():
                        sys.exit(f"missing or invalid config key `{key}.{field}` in .omi/config.json. Nothing changed.")
                if kind == "models":
                    mapping = "codex_models" if tool == "codex" else "models"
                    models = (tools.DEFAULT_MODELS if tool == "claude" else {}) | config.get(mapping, {})
                    if not models.get(name):
                        sys.exit(f"missing config key `{mapping}.{name}` for `{key}` in .omi/config.json. Nothing changed.")
                    try:
                        model = tools.resolve_model(root, name, tool)
                    except SystemExit as exc:
                        sys.exit(f"invalid config key `{mapping}.{name}` for `{key}`: {exc}")
                    lines.append(f"- {name}: {model}; fits: {note['fits']}; avoid: {note['avoid']}")
                else:
                    lines.append(f"- effort {name}; fits: {note['fits']}; avoid: {note['avoid']}")
    out = Path(root) / ".omi" / "agents" / "CATALOG.md"
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {out} ({count} roles)")


def task_skill_ids(root, m):
    """The task's role default skills plus its own `skills:`, without duplicates; the role must exist."""
    role = get_role(root, m.get("role") or "omi-agent-engineer")
    return list(dict.fromkeys([*task_skills(role), *task_skills(m)]))
