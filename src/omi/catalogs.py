SKILL_LIMITS = {"tokens": 6000, "skill_tokens": 2000}  # .omi/config.json "skill_limits" overrides (PO only)


def skill_files(skill_dir):
    """SKILL.md plus the references its frontmatter declares (`references: a.md, b.md`, relative to the skill)."""
    d = Path(skill_dir)
    refs = [d / r for r in core.split(core.meta(d / "SKILL.md").get("references"))]
    for r in refs:
        if ".." in r.relative_to(d).parts or not r.is_file():
            sys.exit(f"skill {d.name}: bad reference {r.relative_to(d)}")
    return [d / "SKILL.md", *refs]


def skill_dirs(root):
    """{id: dir} for every .omi/skills/<group>/<id>/SKILL.md; ids are unique across groups."""
    found = {}
    for f in sorted((Path(root) / ".omi" / "skills").glob("*/*/SKILL.md")):
        if f.parent.name in found:
            sys.exit(f"duplicate skill id {f.parent.name}: {found[f.parent.name]} and {f.parent}")
        found[f.parent.name] = f.parent
    return found


def skills_catalog(root):
    """Write .omi/skills/CATALOG.md: one line per skill, `- id (group): when to use [~N tokens]`."""
    lines = ["# Skill catalog", "", "<!-- generated by `python -m omi skills`; do not edit -->"]
    for sid, d in skill_dirs(root).items():
        when = " ".join(core.meta(d / "SKILL.md").get("description", "").split()) or "(no description)"
        lines.append(f"- {sid} ({d.parent.name}): {when} [~{core.tokens(*skill_files(d))} tokens]")
    out = Path(root) / ".omi" / "skills" / "CATALOG.md"
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {out} ({len(lines) - 3} skills)")


SKILL_KEYS = ("id", "group", "description", "tokens", "tools", "source_repo", "source_ref", "source_file", "source_license", "source_use")
SKILL_SECTIONS = ("when to use", "when not to use", "inputs", "steps", "outputs and evidence", "stop and escalate", "tools needed")
SKILL_USES = ("reference", "adapt", "rewrite")
SKILL_WIDENING = re.compile(  # phrases by which a skill would widen permissions or scope
    r"ignore (the )?(task )?scope|outside (the )?scope|widen(ing)? (the )?(scope|permissions)|"
    r"disable (the )?(guard|hook)|--dangerously|bypass(ing)? (the )?(guard|permissions?)|skip (the )?guard", re.I)
SKILL_REF = re.compile(r"[0-9a-f]{7,40}|v?\d+(\.\d+)+", re.I)  # commit SHA or version tag, never a branch
SKILL_FORBIDDEN_KEYS = ("allowed-tools", "allowed_tools", "permissions", "scope")


def validate_skill(d, cap):
    """Problems of one skill dir against the contract, as a list of strings (empty = valid)."""
    d = Path(d)
    m = core.meta(d / "SKILL.md")
    body = m["_text"].split("---", 2)[-1]
    errs = [f"missing frontmatter `{k}`" for k in SKILL_KEYS if not m.get(k)]
    if m.get("id") and m["id"] != d.name:
        errs.append(f"id `{m['id']}` differs from directory `{d.name}`")
    if d.name and not d.name.startswith("omi-skill-"):
        errs.append(f"id `{d.name}` must start with `omi-skill-`")
    if m.get("group") and m["group"] != d.parent.name:
        errs.append(f"group `{m['group']}` differs from directory `{d.parent.name}`")
    if m.get("source_use") and m["source_use"] not in SKILL_USES:
        errs.append(f"source_use `{m['source_use']}` is not one of {'|'.join(SKILL_USES)}")
    if m.get("source_ref") and not SKILL_REF.fullmatch(m["source_ref"]):
        errs.append(f"source_ref `{m['source_ref']}` is not a 7-40 char hex SHA or a version tag like v1.2")
    if m.get("tokens") and not m["tokens"].isdigit():
        errs.append("tokens is not a number")
    heads = [h.strip().lower() for h in re.findall(r"^#{1,6}\s+(.+)$", body, re.M)]
    errs += [f"missing section `{s}`" for s in SKILL_SECTIONS if s not in heads]
    errs += [f"frontmatter `{k}` would widen permissions or scope" for k in SKILL_FORBIDDEN_KEYS if k in m]
    # ponytail: heuristic phrase match, weak against evasion; the frontmatter key check above is the real guard
    errs += [f"widens permissions or scope: `{x.group(0)}`" for x in SKILL_WIDENING.finditer(body)]
    try:
        n = core.tokens(*skill_files(d))
    except SystemExit as e:
        return errs + [str(e)]
    if n > cap:
        errs.append(f"{n} tokens, at most {cap} per skill")
    return errs


def check_all_skills(root):
    """Validate every skill under root; exits non-zero listing all problems."""
    cap = skill_limits(root)["skill_tokens"]
    dirs = skill_dirs(root)
    bad = [f"{sid}: {e}" for sid, d in dirs.items() for e in validate_skill(d, cap)]
    if bad:
        sys.exit("skills check failed:\n" + "\n".join(bad))
    print(f"skills ok ({len(dirs)} checked)")


def skill_limits(root):
    cfg = Path(root) / ".omi" / "config.json"
    over = json.loads(cfg.read_text(encoding="utf-8")).get("skill_limits", {}) if cfg.exists() else {}
    return SKILL_LIMITS | over


def task_skills(m):
    return core.split((m.get("skills") or "").strip().strip("[]"))


def check_skills(root, ids):
    """Files of the declared skills; exits on an unknown id, a skill missing from the catalog, or over budget."""
    root = Path(root)
    dirs = skill_dirs(root)
    cat = root / ".omi" / "skills" / "CATALOG.md"
    listed = set(re.findall(r"^- (\S+) ", cat.read_text(encoding="utf-8"), re.M)) if cat.exists() else set()
    for sid in ids:
        if sid not in dirs:
            sys.exit(f"unknown skill {sid}: no .omi/skills/<group>/{sid}/SKILL.md (skill ids start with omi-skill-)")
        if sid not in listed:
            sys.exit(f"skill {sid} is missing from the catalog; run `python -m omi skills`")
    lim = skill_limits(root)
    per = {sid: core.tokens(*skill_files(dirs[sid])) for sid in ids}
    total = sum(per.values())
    for sid, n in per.items():
        if n > lim["skill_tokens"]:
            sys.exit(f"skill budget: {sid} is {n} tokens, at most {lim['skill_tokens']} per skill. Only the PO can raise it.")
    if total > lim["tokens"]:
        sys.exit(f"skill budget: {total} tokens in total, at most {lim['tokens']}. Only the PO can raise it.")
    return [f for sid in ids for f in skill_files(dirs[sid])]


