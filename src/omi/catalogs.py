def task_references(root, m):
    refs = load_references(root)
    cat = Path(root) / ".omi" / "references" / "CATALOG.md"
    listed = set(re.findall(r"^- ([^:]+):", cat.read_text(encoding="utf-8"), re.M)) if cat.exists() else set()
    files = []
    for rid in core.split((m.get("refs") or "").strip().strip("[]")):
        if rid not in refs:
            sys.exit(f"unknown reference {rid}: no .omi/references/{rid}.md")
        f, errs = refs[rid]
        if errs:
            sys.exit(f"reference {rid}: " + "; ".join(errs))
        if rid not in listed:
            sys.exit(f"reference {rid} is missing from the catalog; run `python -m omi references`")
        files.append(f)
    return files


