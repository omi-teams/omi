USAGE_HEAD = "| role | model | effort | input | output | cache | duration |"


def parse_usage(tool, out):
    """(result text, input, output, cache) from harness output; numbers are None when it gave none."""
    rows = []
    for line in (out or "").splitlines():
        try:
            rows.append(json.loads(line))
        except ValueError:
            pass
    if not rows and out:
        try:
            rows = [json.loads(out)]
        except ValueError:
            pass
    rows = [r for r in rows if isinstance(r, dict)]
    if tool == "claude":
        r = next((r for r in reversed(rows) if isinstance(r.get("usage"), dict)), None)
        if not r:
            return None, None, None, None
        u = r["usage"]
        return (r.get("result"), u.get("input_tokens"), u.get("output_tokens"),
                (u.get("cache_read_input_tokens") or 0) + (u.get("cache_creation_input_tokens") or 0))
    done = [r["usage"] for r in rows if r.get("type") == "turn.completed" and isinstance(r.get("usage"), dict)]
    text = next((r["item"].get("text") for r in reversed(rows)
                 if isinstance(r.get("item"), dict) and r["item"].get("type") == "agent_message"), None)
    if not done:
        return text, None, None, None
    return (text, sum(u.get("input_tokens") or 0 for u in done), sum(u.get("output_tokens") or 0 for u in done),
            sum(u.get("cached_input_tokens") or 0 for u in done))


def record_usage(task, role, model, effort, nums, seconds):
    """Append one row to the task file's `## Usage` table (created at the end if missing)."""
    if not task.exists():
        return
    cell = lambda v: "n/a" if v is None else str(v)
    row = f"| {role} | {model} | {effort or 'n/a'} | {cell(nums[0])} | {cell(nums[1])} | {cell(nums[2])} | {round(seconds)}s |"
    text = task.read_text(encoding="utf-8")
    if "\n## Usage" in text:
        head, _, rest = text.partition("\n## Usage")
        body, sep, tail = rest.partition("\n## ")
        text = f"{head}\n## Usage{body.rstrip()}\n{row}\n" + (f"\n## {tail}" if sep else "")
    else:
        text = f"{text.rstrip()}\n\n## Usage\n{USAGE_HEAD}\n|---|---|---|---|---|---|---|\n{row}\n"
    task.write_text(text, encoding="utf-8")


def usage_totals(text):
    """One line for status: summed tokens over the Usage rows and reviewer rounds, or ''."""
    _, sep, rest = text.partition("\n## Usage")
    if not sep:
        return ""
    rows = [[c.strip() for c in l.strip().strip("|").split("|")] for l in rest.split("\n## ", 1)[0].splitlines()
            if l.startswith("|") and not l.startswith("|---") and not l.startswith("| role")]
    rows = [r for r in rows if len(r) == 7]
    tot = [sum(int(r[i]) for r in rows if r[i].isdigit()) if any(r[i].isdigit() for r in rows) else "n/a" for i in (3, 4, 5)]
    return (f"usage: {len(rows)} runs, in {tot[0]} out {tot[1]} cache {tot[2]}, "
            f"review rounds: {sum(r[0] == 'reviewer' for r in rows)}")


def main_checkout(wt):
    common = git(wt, "rev-parse", "--path-format=absolute", "--git-common-dir")
    return Path(common).parent if common else None


def image_repo(main):
    return f"omi-worker-{repo_label(main)}"


def image_tag(main):
    d = main / "docker"
    if not (d / "Dockerfile").exists():
        d = TEMPLATE / "docker"
    return d, f"{image_repo(main)}:" + hashlib.sha256((d / "Dockerfile").read_bytes()).hexdigest()[:12]


def old_images(main, keep):
    """Images of this repo's worker other than `keep`."""
    r = subprocess.run(["docker", "images", "--filter", f"label=omi-repo={repo_label(main)}",
                        "--format", "{{.Repository}}:{{.Tag}}"],
                       capture_output=True, text=True, errors="replace")
    return [i for i in r.stdout.split() if i != keep and i.startswith(image_repo(main) + ":")]


def ensure_image(main):
    d, tag = image_tag(main)
    if subprocess.run(["docker", "image", "inspect", tag], capture_output=True).returncode:
        r = subprocess.run(["docker", "build", "-t", tag, "--label", "omi-worker=1",
                            "--label", f"omi-repo={repo_label(main)}", str(d)],
                           capture_output=True, text=True, errors="replace")
        if r.returncode:
            print(r.stdout, r.stderr, sep="\n", file=sys.stderr)
            sys.exit("docker build failed.")
        for i in old_images(main, tag):
            subprocess.run(["docker", "rmi", i], capture_output=True)
    return tag


def clean(cwd=".", all_images=False):
    """Remove this repo's worker containers and every worker image except the current one (all_images: that too)."""
    main = main_checkout(cwd) or Path(cwd).resolve()
    r = subprocess.run(["docker", "ps", "-a", "-q", "--filter", "label=omi-worker=1",
                        "--filter", f"label=omi-repo={repo_label(main)}"],
                       capture_output=True, text=True, errors="replace")
    ids = r.stdout.split()
    if ids:
        subprocess.run(["docker", "rm", "-f", *ids], capture_output=True)
    imgs = old_images(main, None if all_images else image_tag(main)[1])
    for i in imgs:
        subprocess.run(["docker", "rmi", i], capture_output=True)
    print(f"removed {len(ids)} container(s), {len(imgs)} image(s)")


def out_of_scope(wt, tid, committed=False):
    """Changed paths in wt that the task's scope (read from development) does not allow; committed: also the branch's commits."""
    shown = git(wt, "show", f"development:.omi/tasks/{tid}.md")
    globs = split(parse(shown).get("scope")) if shown else []
    r = subprocess.run(["git", "-C", str(wt), "status", "--porcelain", "-z", "-uall", "--no-renames"],
                       capture_output=True, text=True)
    paths = [e[3:] for e in r.stdout.split("\0") if e]
    if committed:
        d = subprocess.run(["git", "-C", str(wt), "diff", "--name-only", "-z", "--no-renames", "development...HEAD"],
                           capture_output=True, text=True)
        paths += [p for p in d.stdout.split("\0") if p and p not in paths]
    def bad(p):
        if p == f".omi/tasks/{tid}.md":
            return False
        if os.path.islink(Path(wt) / p):  # host tools could follow it out of the worktree
            return True
        if any(c.lower().startswith(".git") or re.fullmatch(r"(?i)git[^~/]*~\d+(\.[^/]*)?", c) for c in p.split("/")) and p not in globs:
            return True  # .gitattributes, .githooks..., and their Windows 8.3 names (GIT~1): host git processes them; only an exact scope entry allows
        return not any(PurePosixPath(p).full_match(g) for g in globs)
    return [p for p in paths if bad(p)]


def test_command(wt, main):
    """`test` from .omi/config.json, else tests/test_omi.py if present, else pytest."""
    cfg = Path(main) / ".omi" / "config.json"
    cmd = (json.loads(cfg.read_text(encoding="utf-8")) if cfg.exists() else {}).get("test")
    argv = cmd.split() if cmd else ["python", *(["tests/test_omi.py"] if (Path(wt) / "tests" / "test_omi.py").exists()
                                               else ["-m", "pytest", "-q"])]
    return [sys.executable if argv[0] == "python" else argv[0], *argv[1:]]


def deterministic_checks(wt, main, tid):
    """Problems a script can find in the diff before a read role is started (empty = start the role)."""
    problems = []
    bad = out_of_scope(wt, tid, committed=True)
    if bad:
        problems.append("scope check: outside scope: " + ", ".join(bad))
    saved, sys.stdout = sys.stdout, io.StringIO()
    try:
        check_all_skills(wt)
    except SystemExit as e:
        problems.append(f"skills --check: {e}")
    finally:
        sys.stdout = saved
    if (Path(wt) / ".omi" / "workflows").is_dir():
        r = subprocess.run([sys.executable, "-m", "omi", "workflows", "--check"], cwd=wt, capture_output=True, text=True)
        if r.returncode:
            problems.append("workflows --check: " + (r.stdout + r.stderr).strip())
    r = subprocess.run(test_command(wt, main), cwd=wt, capture_output=True, text=True, errors="replace")
    if r.returncode:
        problems.append("tests failed:\n" + "\n".join((r.stdout + r.stderr).strip().splitlines()[-20:]))
    return problems


def need_docker():
    if not shutil.which("docker") or subprocess.run(["docker", "info"], capture_output=True).returncode:
        sys.exit("Docker is not running; start Docker Desktop and retry. Nothing changed.")


def run_role(role, wt, task_file, model=None, effort=None, tool="claude"):
    wt = Path(wt).resolve()
    main = main_checkout(wt)
    if not main or not (wt / ".git").is_file():
        sys.exit(f"{wt} is not a git worktree. Nothing changed.")
    task = Path(task_file).resolve()
    try:
        task_rel = task.relative_to(wt).as_posix()
    except ValueError:
        sys.exit(f"{task} is not inside {wt}. Nothing changed.")
    if tool not in ("claude", "codex"):
        sys.exit(f"unknown tool `{tool}`: claude or codex. Nothing changed.")
    need_docker()  # read roles too: no host fallback
    secret = token() if tool == "claude" else os.environ.get("OPENAI_API_KEY")
    key = TOKEN_ENV if tool == "claude" else "OPENAI_API_KEY"
    if not secret:
        sys.exit(f"no token: run `omi token set` (Windows) or set {key}. Nothing changed.")
    tm = meta(task) if task.exists() else {}
    am = get_role(main, role)
    get_role(main, tm.get("role") or "engineer")  # unknown task role fails too
    declared = check_skills(wt, list(dict.fromkeys([*task_skills(am), *task_skills(tm)])))  # role defaults count against the budget
    effort = effort or am.get("effort")
    model = resolve_model(main, model or am.get("model"))
    read = am["access"] == "read"
    mounts = []
    if read:
        problems = deterministic_checks(wt, main, task.stem)
        if problems:
            print(f"{role} not started; fix these first:\n" + "\n".join(problems))
            return 4
    image = ensure_image(main)
    env = dict(os.environ)
    env.pop(TOKEN_ENV, None)
    env[key] = secret
    prompt_skills = skill_prompt(wt, declared)
    text = am["_text"]
    tmp = tempfile.TemporaryDirectory() if read else None
    try:
        if read:
            base = git(wt, "merge-base", "development", "HEAD") or "development"
            patch = Path(tmp.name) / "diff.patch"
            patch.write_text(git(wt, "diff", base) or "", encoding="utf-8")
            mounts.append(f"{tmp.name}:/review")
            prompt_skills += "\nDiff: /review/diff.patch (read-only; git does not work in this container)"
        cmd = (engineer_cmd if tool == "claude" else codex_cmd)(text, task_rel, model, effort, prompt_skills)
        t0 = time.monotonic()
        r = subprocess.run(worker_argv(wt, image, cmd, container_name(main.name, role, task.stem, model, effort),
                                         repo_label(main), worker_labels(role, task.stem, model, effort), ro=read,
                                         mounts=mounts, env_names=(key,)),
                            env=env, stdin=subprocess.DEVNULL, stdout=subprocess.PIPE, text=True, errors="replace")
        rc = r.returncode
        result, *nums = parse_usage(tool, r.stdout)
        print(result if result is not None else (r.stdout or ""))
        record_usage(task, role, model, effort, nums, time.monotonic() - t0)
    finally:
        if tmp:
            tmp.cleanup()
    if read:
        return rc
    bad = out_of_scope(wt, task.stem)
    for p in bad:
        print(f"OUT OF SCOPE: {p}")
    return rc or (3 if bad else 0)


def worker(wt, task_file=None, model=None, effort=None, prove=False):
    if not prove:
        return run_role("engineer", wt, task_file, model, effort)
    wt = Path(wt).resolve()
    main = main_checkout(wt)
    if not main or not (wt / ".git").is_file():
        sys.exit(f"{wt} is not a git worktree. Nothing changed.")
    need_docker()
    image = ensure_image(main)
    env = dict(os.environ)
    env.pop(TOKEN_ENV, None)
    script = main / "docker" / "prove.sh"
    script = script if script.exists() else TEMPLATE / "docker" / "prove.sh"
    return subprocess.run(worker_argv(wt, image, ["sh", "-s"], container_name(main.name, "prove"), repo_label(main),
                                 worker_labels("prove", None, None, None)), env=env,
                          input=script.read_bytes().replace(b"\r\n", b"\n")).returncode


